/// Translate an English source string into the active language.
///
/// The English string IS the key: a screen just wraps its text in `.tr`, and any
/// string not yet in the dictionary falls back to English — so the app is always
/// fully usable while translations are filled in over time.
String tr(String en) {
  final lang = LocaleController.instance.lang;
  if (lang == 'en') return en;
  return _translations[lang]?[en] ?? en;
}

extension TrExtension on String {
  /// `'My Wallet'.tr` → the string in the active language.
  String get tr => translate(this);
}

// Kept as a free function too so `translate('x')` reads naturally where an
// extension getter would be awkward.
String translate(String en) => tr(en);

